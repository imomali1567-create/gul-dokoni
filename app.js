// State Management via LocalStorage
const AppState = {
    lang: localStorage.getItem('floralux_lang') || 'uz',
    theme: localStorage.getItem('floralux_theme') || 'light',
    favorites: JSON.parse(localStorage.getItem('floralux_favs') || '[]'),
    cart: JSON.parse(localStorage.getItem('floralux_cart') || '[]')
};

function saveState() {
    localStorage.setItem('floralux_lang', AppState.lang);
    localStorage.setItem('floralux_theme', AppState.theme);
    localStorage.setItem('floralux_favs', JSON.stringify(AppState.favorites));
    localStorage.setItem('floralux_cart', JSON.stringify(AppState.cart));
}

function t(key) {
    return translations[AppState.lang][key] || key;
}

function applyTheme() {
    document.documentElement.setAttribute('data-theme', AppState.theme);
    const themeBtn = document.getElementById('theme-toggle');
    if (themeBtn) {
        themeBtn.textContent = AppState.theme === 'dark' ? '☀️' : '🌙';
    }
}

function toggleTheme() {
    AppState.theme = AppState.theme === 'dark' ? 'light' : 'dark';
    saveState();
    applyTheme();
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        el.setAttribute('placeholder', t(key));
    });
    const langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = AppState.lang;
}

function updateBadges() {
    const favBadge = document.getElementById('fav-badge');
    const cartBadge = document.getElementById('cart-badge');
    if (favBadge) favBadge.textContent = AppState.favorites.length;
    if (cartBadge) cartBadge.textContent = AppState.cart.length;
}

function showToast(msg) {
    let container = document.querySelector('.toast-container');
    if (!container) {
        container = document.createElement('div');
        container.className = 'toast-container';
        document.body.appendChild(container);
    }
    const toast = document.createElement('div');
    toast.className = 'toast';
    toast.textContent = msg;
    container.appendChild(toast);
    setTimeout(() => toast.remove(), 3000);
}

function toggleFavorite(id) {
    const idx = AppState.favorites.indexOf(id);
    if (idx > -1) {
        AppState.favorites.splice(idx, 1);
        showToast(t('toast_fav_rem'));
    } else {
        AppState.favorites.push(id);
        showToast(t('toast_fav_add'));
    }
    saveState();
    updateBadges();
    renderCurrentPageProducts();
}

function addToCart(id) {
    AppState.cart.push(id);
    saveState();
    updateBadges();
    showToast(t('toast_cart_add'));
}

function createProductCardHTML(flower) {
    const isFav = AppState.favorites.includes(flower.id);
    const title = flower.names[AppState.lang] || flower.names.uz;
    const desc = flower.desc[AppState.lang] || flower.desc.uz;
    const catLabel = t('cat_' + flower.category);

    return `
        <div class="product-card">
            <div class="product-img-wrap">
                <img src="${flower.image}" alt="${title}" class="product-img" loading="lazy">
                <button class="fav-toggle ${isFav ? 'active' : ''}" onclick="toggleFavorite(${flower.id})" title="Wishlist">
                    ${isFav ? '❤️' : '🤍'}
                </button>
            </div>
            <div class="product-info">
                <span class="product-category">${catLabel}</span>
                <h3 class="product-title">${title}</h3>
                <p class="product-desc">${desc}</p>
                <div class="product-footer">
                    <span class="product-price">$${flower.price}</span>
                    <button class="btn btn-primary" onclick="addToCart(${flower.id})">
                        🛒 <span>${t('btn_cart')}</span>
                    </button>
                </div>
            </div>
        </div>
    `;
}

function renderCurrentPageProducts() {
    // 1. Home Page Popular Grid
    const popularGrid = document.getElementById('popular-grid');
    if (popularGrid) {
        const popFlowers = flowersData.filter(f => f.popular);
        popularGrid.innerHTML = popFlowers.map(createProductCardHTML).join('');
    }

    // 2. Catalog Page Grid with Filters
    const catalogGrid = document.getElementById('catalog-grid');
    if (catalogGrid) {
        const searchVal = (document.getElementById('search-input')?.value || '').toLowerCase();
        const catVal = document.getElementById('category-filter')?.value || 'all';
        const sortVal = document.getElementById('sort-filter')?.value || 'default';

        let filtered = flowersData.filter(f => {
            const nameMatch = (f.names[AppState.lang] || '').toLowerCase().includes(searchVal);
            const catMatch = catVal === 'all' || f.category === catVal;
            return nameMatch && catMatch;
        });

        if (sortVal === 'asc') filtered.sort((a, b) => a.price - b.price);
        if (sortVal === 'desc') filtered.sort((a, b) => b.price - a.price);

        catalogGrid.innerHTML = filtered.map(createProductCardHTML).join('');
    }

    // 3. Favorites Page Grid
    const favGrid = document.getElementById('favorites-grid');
    const favEmpty = document.getElementById('favorites-empty');
    if (favGrid) {
        const favFlowers = flowersData.filter(f => AppState.favorites.includes(f.id));
        if (favFlowers.length === 0) {
            favGrid.innerHTML = '';
            if (favEmpty) favEmpty.style.display = 'block';
        } else {
            if (favEmpty) favEmpty.style.display = 'none';
            favGrid.innerHTML = favFlowers.map(createProductCardHTML).join('');
        }
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTheme();
    applyTranslations();
    updateBadges();
    renderCurrentPageProducts();

    const themeBtn = document.getElementById('theme-toggle');
    if (themeBtn) themeBtn.addEventListener('click', toggleTheme);

    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => {
            AppState.lang = e.target.value;
            saveState();
            applyTranslations();
            renderCurrentPageProducts();
        });
    }

    // Catalog filters listeners
    ['search-input', 'category-filter', 'sort-filter'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.addEventListener('input', renderCurrentPageProducts);
    });

    // Clear favorites button
    const clearFavBtn = document.getElementById('clear-favs-btn');
    if (clearFavBtn) {
        clearFavBtn.addEventListener('click', () => {
            AppState.favorites = [];
            saveState();
            updateBadges();
            renderCurrentPageProducts();
        });
    }

    // Contact form submission
    const contactForm = document.getElementById('contact-form');
    if (contactForm) {
        contactForm.addEventListener('submit', (e) => {
            e.preventDefault();
            showToast(t('toast_form_ok'));
            contactForm.reset();
        });
    }
});